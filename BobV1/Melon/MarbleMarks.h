static float marbleCell(int i, int j) {
    i = (i + 256) & 255; j = clamp(j, 0, 127);
    uint w = marbleMap[(j * 256 + i) >> 3];
    return float((w >> (4u * uint((j * 256 + i) & 7))) & 15u) * (1.0 / 15.0);
}
// 0...1 coverage of the veins at rest-space point Q.
static float marbleVein(float3 Q) {
    float u = (atan2(Q.x, Q.z) * 0.15915494 + 0.5) * 256.0 - 0.5;
    float t = clamp((Q.y - 0.1039) / 1.2419, 0.0, 1.0);
    float v = t * 128.0 - 0.5;
    int i0 = int(floor(u)), j0 = int(floor(v)); float fu = u - float(i0), fv = v - float(j0);
    float a = mix(marbleCell(i0, j0), marbleCell(i0 + 1, j0), fu), b = mix(marbleCell(i0, j0 + 1), marbleCell(i0 + 1, j0 + 1), fu);
    float m = smoothstep(0.06, 0.50, mix(a, b, fv));
    m *= smoothstep(0.17, 0.23, Q.y);                                  // no vein on the foot soles
    return m;
}

// Marble (body mode 121). `col` is the shaded body colour (the palette's flesh, lit); the vein keeps that light: col * (vein tint / flesh).
static float3 marblePaint(float3 col, float3 Q) {
    const float3 flesh = float3(0.525, 0.863, 0.812), tint = float3(0.97, 1.0, 0.99);
    return mix(col, col * (tint / flesh), 0.92 * marbleVein(Q));
}

