static float cowCell(int i, int j) {
    i = (i + 128) & 127; j = clamp(j, 0, 63);
    uint w = cowMap[(j * 128 + i) >> 3];
    return float((w >> (4u * uint((j * 128 + i) & 7))) & 15u) * (1.0 / 15.0);
}
// 0...1 coverage of the cow patches at rest-space point Q.
static float cowPatch(float3 Q) {
    float u = (atan2(Q.x, Q.z) * 0.15915494 + 0.5) * 128.0 - 0.5;
    float t = clamp((Q.y - 0.1039) / 1.2419, 0.0, 1.0);
    float v = t * 64.0 - 0.5;
    int i0 = int(floor(u)), j0 = int(floor(v)); float fu = u - float(i0), fv = v - float(j0);
    float a = mix(cowCell(i0, j0), cowCell(i0 + 1, j0), fu), b = mix(cowCell(i0, j0 + 1), cowCell(i0 + 1, j0 + 1), fu);
    float f = mix(a, b, fv);
    f += 0.05 * sin(37.0 * Q.x + 23.0 * Q.y + 11.0 * Q.z) * sin(29.0 * Q.z - 31.0 * Q.y + 5.0);          // a torn, ragged edge
    float m = smoothstep(0.46, 0.54, f);
    float2 fp = float2(Q.x / 0.31, (Q.y - 0.80) / 0.23);          // the face stays clear
    m *= 1.0 - (1.0 - smoothstep(0.92, 1.08, length(fp))) * smoothstep(0.02, 0.14, Q.z);
    m *= smoothstep(0.17, 0.23, Q.y);                                  // no patch on the foot soles
    return m;
}

// bm 1 = Moo, 3 = Cocoa, 5 = Blush. `col` is the shaded body colour (the palette's flesh, lit); the patch keeps that light: col * (patch tint / flesh).
static float3 cowPaint(float3 col, float3 Q, float bm) {
    float3 flesh, tint;
    if (bm < 2.0) { flesh = float3(0.957, 0.945, 0.925); tint = float3(0.13, 0.13, 0.16); }          // (the drawing's 0.26 / 0.26 / 0.29, stretched: the jelly shading lifts a patch toward grey)
    else if (bm < 4.0) { flesh = float3(0.953, 0.902, 0.812); tint = float3(0.40, 0.23, 0.16); }
    else { flesh = float3(0.976, 0.890, 0.910); tint = float3(0.90, 0.36, 0.52); }
    return mix(col, col * (tint / flesh), cowPatch(Q));
}

