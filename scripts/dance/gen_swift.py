#!/usr/bin/env python3
"""Writes BobV1/Show/DancePatterns.swift from scripts/dance/patterns.json (run from anywhere).
A pattern is a string of "<slot><L|R>" words: slot counts HALF beats on the song's grid (even = on a beat), L = bass / left foot, R = clap / right foot."""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
data = json.load(open(os.path.join(here, "patterns.json")))
out = os.path.join(here, "..", "..", "BobV1", "Show", "DancePatterns.swift")
lines = ["//", "//  DancePatterns.swift", "//  GENERATED by scripts/dance/gen_swift.py from scripts/dance/patterns.json: do not edit by hand (DancePatternTests fails if the two differ).",
         "//  The Jelly Show's Dance round prompts per song: \"old\" (one per beat), \"calm\" (rests) and \"lively\" (rests and quick doubles).",
         "//  Each pattern is a list of \"<slot><L|R>\" words: slot counts HALF beats on the song's measured grid (even = on a beat), L = left foot (bass), R = right foot (clap).", "//", "",
         "nonisolated enum DancePatternData {", "    static let words: [Int: [String: String]] = ["]
for n in sorted(data, key=int):
    lines.append(f"        {n}: [")
    for name in ("old", "calm", "lively"):
        w = " ".join(f"{p['slot']}{p['foot']}" for p in data[n][name]["prompts"])
        lines.append(f"            \"{name}\": \"{w}\",")
    lines.append("        ],")
lines += ["    ]", "}", ""]
open(out, "w").write("\n".join(lines))
print("wrote", os.path.normpath(out))
